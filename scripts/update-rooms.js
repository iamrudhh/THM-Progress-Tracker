#!/usr/bin/env node
// Regenerates rooms.js from the upstream room list (needs Node 18+, no dependencies).
// Usage: node scripts/update-rooms.js   (or: npm run update-rooms)
const fs = require("fs");
const path = require("path");

const SOURCE = "https://raw.githubusercontent.com/abimelsbk/free-tryhackme-rooms/main/README.md";
const OUT = path.join(__dirname, "..", "rooms.js");
const LINK = /^\s*[-*] (?:\[[ xX]\] )?\[(?:TryHackMe \| )?(.+?)\]\((https:\/\/tryhackme\.com\/room\/[^)]+)\)/;

(async () => {
  const res = await fetch(SOURCE);
  if (!res.ok) throw new Error(`Could not download the room list (HTTP ${res.status})`);

  let category = null, started = false;
  const seen = new Set(), rows = [];

  for (const line of (await res.text()).split("\n")) {
    const h = line.match(/^## (.+)/);
    if (h) {
      category = h[1].trim();
      if (category === "Intro Rooms") started = true;
      if (category === "About") break;
      continue;
    }
    if (!started) continue;
    const m = line.match(LINK);
    if (!m || seen.has(m[2])) continue;
    seen.add(m[2]);
    rows.push([category, m[1].trim(), m[2].split("/").pop()]);
  }

  if (rows.length < 100) throw new Error("Parsed too few rooms; the upstream format may have changed.");

  const body = rows.map(r => JSON.stringify(r)).join(",\n");
  const header =
    "// [category, name, room slug]\n" +
    "// Generated by scripts/update-rooms.js from github.com/abimelsbk/free-tryhackme-rooms. Do not edit by hand.\n";
  fs.writeFileSync(OUT, `${header}const ROOMS = [\n${body}\n];\n`);
  console.log(`Wrote ${rows.length} rooms to rooms.js`);
})().catch(e => { console.error(e.message); process.exit(1); });
